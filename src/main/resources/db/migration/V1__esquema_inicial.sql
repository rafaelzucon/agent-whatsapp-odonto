-- =============================================================================
-- V1__esquema_inicial.sql
-- Esquema inicial do agente de WhatsApp do consultório odontológico.
--
-- Dados pessoais (RG, nome, data de nascimento, responsável, textos de queixa,
-- mensagens e dados da conversa) são gravados cifrados pela aplicação com
-- AES-256-GCM. A busca por RG usa um HMAC-SHA256 do documento (rg_hash), nunca o
-- valor em claro. Datas e horas são timestamptz (instantes em UTC); a aplicação
-- converte para o fuso do consultório.
-- =============================================================================

CREATE SEQUENCE prontuario_numero_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE problema_odontologico (
    codigo          varchar(60)  PRIMARY KEY,
    nome            varchar(150) NOT NULL,
    descricao       text         NOT NULL,
    especialidade   varchar(100) NOT NULL,
    prioridade      varchar(20)  NOT NULL CHECK (prioridade IN ('EMERGENCIA', 'URGENCIA', 'ROTINA')),
    cid10           varchar(10),
    palavras_chave  text         NOT NULL DEFAULT '',
    ativo           boolean      NOT NULL DEFAULT true
);

COMMENT ON COLUMN problema_odontologico.palavras_chave IS 'Palavras-chave separadas por ponto e vírgula.';

CREATE TABLE paciente (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rg_hash                  varchar(64)  NOT NULL UNIQUE,
    rg_cifrado               text         NOT NULL,
    nome_cifrado             text         NOT NULL,
    data_nascimento_cifrada  text         NOT NULL,
    responsavel_cifrado      text,
    consentimento_lgpd       boolean      NOT NULL,
    data_consentimento       timestamptz,
    data_cadastro            timestamptz  NOT NULL
);

CREATE TABLE paciente_telefone (
    paciente_id  bigint      NOT NULL REFERENCES paciente (id) ON DELETE CASCADE,
    wa_id        varchar(15) NOT NULL,
    PRIMARY KEY (paciente_id, wa_id)
);

CREATE INDEX idx_paciente_telefone_wa_id ON paciente_telefone (wa_id);

CREATE TABLE prontuario (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id    bigint      NOT NULL UNIQUE REFERENCES paciente (id),
    numero         varchar(20) NOT NULL UNIQUE,
    data_abertura  timestamptz NOT NULL
);

CREATE TABLE consulta (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id  bigint      NOT NULL REFERENCES paciente (id),
    queixa_id    bigint,
    inicio       timestamptz NOT NULL,
    fim          timestamptz NOT NULL,
    status       varchar(20) NOT NULL CHECK (status IN ('AGENDADA', 'CANCELADA', 'REALIZADA', 'FALTOU')),
    criada_em    timestamptz NOT NULL,
    CHECK (fim > inicio)
);

-- Agenda única: no máximo uma consulta AGENDADA por horário de início (proteção contra corrida).
CREATE UNIQUE INDEX uk_consulta_inicio_agendada ON consulta (inicio) WHERE status = 'AGENDADA';
CREATE INDEX idx_consulta_paciente ON consulta (paciente_id);
CREATE INDEX idx_consulta_inicio ON consulta (inicio);

CREATE TABLE queixa_relatada (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prontuario_id    bigint       NOT NULL REFERENCES prontuario (id),
    texto_cifrado    text         NOT NULL,
    problema_codigo  varchar(60)  NOT NULL REFERENCES problema_odontologico (codigo),
    prioridade       varchar(20)  NOT NULL CHECK (prioridade IN ('EMERGENCIA', 'URGENCIA', 'ROTINA')),
    confianca        double precision NOT NULL CHECK (confianca BETWEEN 0 AND 1),
    origem           varchar(20)  NOT NULL CHECK (origem IN ('IA', 'PALAVRA_CHAVE', 'MANUAL')),
    data_registro    timestamptz  NOT NULL,
    consulta_id      bigint REFERENCES consulta (id)
);

CREATE INDEX idx_queixa_prontuario ON queixa_relatada (prontuario_id);

ALTER TABLE consulta ADD CONSTRAINT fk_consulta_queixa FOREIGN KEY (queixa_id) REFERENCES queixa_relatada (id);

CREATE TABLE bloqueio_agenda (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio  timestamptz  NOT NULL,
    fim     timestamptz  NOT NULL,
    motivo  varchar(200) NOT NULL,
    CHECK (fim > inicio)
);

CREATE INDEX idx_bloqueio_periodo ON bloqueio_agenda (inicio, fim);

CREATE TABLE conversa (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wa_id                 varchar(15) NOT NULL UNIQUE,
    etapa                 varchar(60) NOT NULL,
    dados_cifrados        text        NOT NULL,
    tentativas_invalidas  integer     NOT NULL DEFAULT 0,
    ultima_interacao      timestamptz NOT NULL,
    iniciada_em           timestamptz NOT NULL
);

CREATE INDEX idx_conversa_ultima_interacao ON conversa (ultima_interacao);

CREATE TABLE mensagem (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wa_message_id  varchar(255) UNIQUE,
    wa_id          varchar(15) NOT NULL,
    direcao        varchar(10) NOT NULL CHECK (direcao IN ('RECEBIDA', 'ENVIADA')),
    tipo           varchar(10) NOT NULL CHECK (tipo IN ('TEXTO', 'AUDIO', 'OUTRO')),
    texto_cifrado  text,
    midia_id       varchar(100),
    automatica     boolean     NOT NULL,
    criada_em      timestamptz NOT NULL
);

CREATE INDEX idx_mensagem_criada_em ON mensagem (criada_em);
CREATE INDEX idx_mensagem_wa_id ON mensagem (wa_id);
